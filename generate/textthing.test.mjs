// Text -> thing: a request file becomes a thing, failures leave a report, and the watcher picks requests up
// without building the same id twice (fake claude, test-bin/).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
process.env.PATH = join(import.meta.dirname, 'test-bin') + ':' + process.env.PATH;
delete process.env.KRITZEL_MODEL; delete process.env.KRITZEL_DRAFT_MODEL;
const { processTextRequest } = await import('./generate.mjs');
const lantern = `// parts: body = a short round base
// parts: glass = a tall glass box above it
// parts: roof = a small pointed lid
// parts: flame = a glowing drop inside the glass
export const meta = { name: 'Laterne', drawing: 'a lantern with a glowing flame', paper: { x: 0.5, y: 0.5 } };
export function build(ctx) {
  const { THREE, world, mat, shadowAll } = ctx;
  const g = new THREE.Group();
  const base = new THREE.Mesh(new THREE.CylinderGeometry(0.3, 0.34, 0.12, 12), mat(0x8a5a3b));
  base.position.y = 0.06;
  const glass = new THREE.Mesh(new THREE.CylinderGeometry(0.24, 0.24, 0.7, 12), mat(0xfff0c0, { emissive: 0xffc36a, emissiveIntensity: 1.2 }));
  glass.position.y = 0.47;
  const roof = new THREE.Mesh(new THREE.ConeGeometry(0.34, 0.22, 12), mat(0x8a5a3b));
  roof.position.y = 0.93;
  const flame = new THREE.Mesh(new THREE.SphereGeometry(0.09, 10, 8), mat(0xffb347, { emissive: 0xff8a3a, emissiveIntensity: 2 }));
  flame.position.y = 0.44;
  g.add(base, glass, roof, flame);
  shadowAll(g); world.add(g);
  return { actors: [], obstacles: [{ x: 0, z: 0, r: 0.4 }], spots: [],
    light: { kind: 'lamp', object3D: flame, color: 0xffa54a, intensity: 1, range: 6 } };
}`;

const dirs = () => {
  const dir = mkdtempSync(join(tmpdir(), 'kritzel-text-'));
  for (const d of ['things', 'reports', 'requests']) mkdirSync(join(dir, d));
  return dir;
};
const request = (dir, id, text = 'eine Laterne', extra = {}) => {
  writeFileSync(join(dir, 'requests', id + '.json'), JSON.stringify({ id, text, lang: 'de', requested_at: '2026-10-19T18:40:12Z', ...extra }));
  return join(dir, 'requests', id + '.json');
};

test('a typed request becomes things/laterne.js, with a report of the call and the checks', async () => {
  const dir = dirs();
  try {
    writeFileSync(join(dir, 'reply.txt'), `SEEN: [{"de": "eine Laterne", "en": "a lantern", "den": "die Laterne", "the": "the lantern", "name_en": "Lantern"}]\n### NEW\n${lantern}`);
    process.env.FAKE_CLAUDE_REPLY = join(dir, 'reply.txt');
    const r = await processTextRequest(request(dir, 'text-20261019-184012'), { thingsDir: join(dir, 'things'), reportsDir: join(dir, 'reports') });
    assert.equal(r.error, undefined, r.error);
    assert.deepEqual(r.written.map(w => w.file), ['laterne.js']);
    const code = readFileSync(join(dir, 'things', 'laterne.js'), 'utf8');
    assert.match(code, /^\/\/ generated by generate\/ from frames\/requests\/text-20261019-184012\.json/m);
    assert.match(code, /name: 'Laterne'/);
    const saved = JSON.parse(readFileSync(join(dir, 'reports', 'text-20261019-184012.json'), 'utf8'));
    assert.equal(saved.request.text, 'eine Laterne');
    assert.equal(saved.request.lang, 'de');
    assert.equal(saved.written[0].file, 'laterne.js');
    assert.equal(saved.calls.length, 1);
    assert.equal(typeof saved.calls[0].seconds, 'number');
    assert.equal(saved.error, undefined);
    assert.equal(saved.finished !== undefined, true);
  } finally { delete process.env.FAKE_CLAUDE_REPLY; rmSync(dir, { recursive: true, force: true }); }
});

test('a request with no text fails loudly, writes its report and asks no model', async () => {
  const dir = dirs();
  const log = join(dir, 'prompts.jsonl');
  try {
    process.env.FAKE_CLAUDE_LOG = log;
    const r = await processTextRequest(request(dir, 'text-20261019-184013', ''), { thingsDir: join(dir, 'things'), reportsDir: join(dir, 'reports') });
    assert.match(r.error, /say what to build/);
    const saved = JSON.parse(readFileSync(join(dir, 'reports', 'text-20261019-184013.json'), 'utf8'));
    assert.match(saved.error, /say what to build/);
    assert.equal(saved.written.length, 0);
    assert.equal(existsSync(log), false);
    assert.deepEqual(readdirSync(join(dir, 'things')), []);
  } finally { delete process.env.FAKE_CLAUDE_LOG; rmSync(dir, { recursive: true, force: true }); }
});

test('an UNCLEAR reply is a visible failure, not a silent empty success', async () => {
  const dir = dirs();
  try {
    writeFileSync(join(dir, 'reply.txt'), 'UNCLEAR: a sword | a weapon, not for the book\nKIDS: {"de": "Das kommt nicht ins Buch.", "en": "That does not go in the book."}');
    process.env.FAKE_CLAUDE_REPLY = join(dir, 'reply.txt');
    const r = await processTextRequest(request(dir, 'text-20261019-184014', 'a sword'), { thingsDir: join(dir, 'things'), reportsDir: join(dir, 'reports') });
    assert.match(r.error, /cannot build this: a sword/);
    assert.deepEqual(readdirSync(join(dir, 'things')), []);
  } finally { delete process.env.FAKE_CLAUDE_REPLY; rmSync(dir, { recursive: true, force: true }); }
});

test('a frame report with the same timestamp does not swallow a text request', async () => {
  const dir = dirs();
  try {
    // the capture watcher's report for a frame at the same second: the request id has its own namespace
    writeFileSync(join(dir, 'reports', '20261019-184012.json'), JSON.stringify({ frame: '20261019-184012.jpg', written: [] }));
    writeFileSync(join(dir, 'reply.txt'), `### NEW\n${lantern}`);
    process.env.FAKE_CLAUDE_REPLY = join(dir, 'reply.txt');
    const r = await processTextRequest(request(dir, 'text-20261019-184012'), { thingsDir: join(dir, 'things'), reportsDir: join(dir, 'reports') });
    assert.equal(r.error, undefined, r.error);
    assert.deepEqual(r.written.map(w => w.file), ['laterne.js']);
    assert.ok(existsSync(join(dir, 'reports', 'text-20261019-184012.json')));
  } finally { delete process.env.FAKE_CLAUDE_REPLY; rmSync(dir, { recursive: true, force: true }); }
});

test('the watcher picks up a request, and a second look at the same id builds it only once', async () => {
  const dir = dirs();
  const log = join(dir, 'prompts.jsonl');
  writeFileSync(join(dir, 'reply.txt'), `### NEW\n${lantern}`);
  const settled = join(dir, 'settled'); mkdirSync(settled);
  // the watcher-level collision: a frame report with the same timestamp must not make takeRequests skip the text id
  writeFileSync(join(dir, 'reports', '20261019-184015.json'), JSON.stringify({ frame: '20261019-184015.jpg', written: [] }));
  const child = spawn(process.execPath, [join(import.meta.dirname, 'generate.mjs'), '--watch', settled,
    '--requests', join(dir, 'requests'), '--things', join(dir, 'things'), '--reports', join(dir, 'reports')], {
    env: { ...process.env, FAKE_CLAUDE_REPLY: join(dir, 'reply.txt'), FAKE_CLAUDE_LOG: log }, stdio: ['ignore', 'pipe', 'pipe'],
  });
  let out = '';
  child.stdout.on('data', d => { out += d; });
  child.stderr.on('data', d => { out += d; });
  try {
    const req = request(dir, 'text-20261019-184015');
    for (let i = 0; i < 100 && !existsSync(join(dir, 'reports', 'text-20261019-184015.json')); i++) await new Promise(ok => setTimeout(ok, 100));
    assert.ok(existsSync(join(dir, 'reports', 'text-20261019-184015.json')), out);
    assert.ok(existsSync(join(dir, 'things', 'laterne.js')), out);
    const calls = readFileSync(log, 'utf8').trim().split('\n').length;
    assert.equal(calls, 1);
    // the same request seen again (a restart, a duplicate) is not built twice
    writeFileSync(req, readFileSync(req, 'utf8'));
    await new Promise(ok => setTimeout(ok, 1200));
    assert.equal(readFileSync(log, 'utf8').trim().split('\n').length, 1);
  } finally {
    child.kill('SIGTERM');
    await new Promise(ok => child.once('close', ok));
    rmSync(dir, { recursive: true, force: true });
  }
});
